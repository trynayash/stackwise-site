/** The illustrative icon on a card: the StackWise glass icon for `icon`, or the line icon in a tile as a fallback. */
export function FeatureIcon({ icon, size = 60, className }: { icon: IconSvgElement; size?: number; className?: string }) {
    const name = glassFor.get(icon);
    if (name) return <GlassIcon name={name} size={size} className={className} />;
    return (
        <IconTile size="lg" className={className}>
            <Icon icon={icon} size={22} />
        </IconTile>
    );
}
